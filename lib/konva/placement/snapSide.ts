// ============================================================
// 「スナップ先のどちら側にカーソルがあるか」— 唯一の定義 (= P-4)
//
// ■ 何を決めるか
// 矩形の部材を線（手摺）へ寄せるとき、**矩形のどの辺を線に乗せるか**。
//   カーソルが線より下にある → 矩形の**上辺**を線に乗せる（線の下側に置かれる）
//   カーソルが線より上にある → 矩形の**下辺**を線に乗せる（線の上側に置かれる）
// 左右も同じ考え方。
//
// ■ なぜ「どちら側か」で決めるのか（四隅までの距離ではなく）
// 距離で選ぶと、境界が**矩形の中心を通る十字**に来る。アンチは 400×1800 のように
// 細長いので、長辺方向の境界が中央に来てしまい、少し動かすだけで基点が入れ替わる。
// 「どちら側か」なら境界は**線そのもの**にあり、
//   ・境界が「線の上に置きたいか下に置きたいか」という意図と一致する
//   ・カーソルを動かしたときの切り替わりが 1 回で済む（ヒステリシスが要らない）
//
// ■ 使っているところ
//   ・アンチ  … lib/konva/placement/antiSnap.ts
//   ・階段    … lib/konva/planeParts.ts の snapStairToCell
// どちらかを直すときは、もう一方も必ず見ること。
// ============================================================

/**
 * 線に矩形を寄せたときの、矩形の先頭側の座標（左上を表す軸の値）。
 *
 * @param cursorAcross  線に直交する向きのカーソル座標
 * @param railAt        線の位置（その軸の値）
 * @param size          その向きの矩形の寸法
 * @returns 矩形の先頭側（上辺 or 左辺）の座標
 *
 * カーソルが線と同じか奥（>=）なら、矩形は線から**奥へ**伸びる（先頭＝線の位置）。
 * 手前なら、矩形は線から**手前へ**伸びる（先頭＝線 − 寸法）。
 * 境界（cursorAcross === railAt）は「奥へ」に倒す。どちらでも辺は線に乗るので、
 * 倒す向きを決め打ちしておけば、境界上で値が揺れない。
 */
export function rectLeadingEdge(
  cursorAcross: number, railAt: number, size: number,
): number {
  return cursorAcross >= railAt ? railAt : railAt - size;
}

/** どちら側に置かれるか（表示・テストで基点を名指しするのに使う）。 */
export type SnapSide = 'far' | 'near';

/**
 * カーソルが線のどちら側にあるか。
 *   'far'  … 線と同じか奥（矩形は線から奥へ伸びる＝先頭辺が線に乗る）
 *   'near' … 手前（矩形は線から手前へ伸びる＝末尾辺が線に乗る）
 */
export const snapSideOf = (cursorAcross: number, railAt: number): SnapSide =>
  cursorAcross >= railAt ? 'far' : 'near';
